"""Quan (2005) ICD-9-CM / ICD-10 mappings for Charlson and Elixhauser comorbidities.

Reference: Quan H, et al. "Coding algorithms for defining comorbidities in
ICD-9-CM and ICD-10 administrative data." Med Care. 2005;43(11):1130-9.

Codes here are DOT-LESS prefixes, matching how MIMIC-IV stores icd_code.
A diagnosis matches a category if its code startswith any prefix in the list.
"""


def _rng(prefix, lo, hi, width):
    """Expand an inclusive numeric range into zero-padded dot-less prefixes."""
    return [f"{prefix}{i:0{width}d}" for i in range(lo, hi + 1)]


